"""Actual isolated Chromium browser journey checks (not a production penetration test)."""
from playwright.sync_api import sync_playwright
import json
import os
BASE=os.environ.get('OJ_E2E_BASE','http://127.0.0.1:8809').rstrip('/')
passes=[]
def ok(label,condition):
    assert condition, label
    passes.append(label)
    print('PASS '+label)
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
    context=browser.new_context(accept_downloads=True,viewport={'width':1360,'height':900})
    page=context.new_page()
    errs=[]
    page.on('pageerror',lambda e: errs.append(str(e)))
    page.goto(BASE+'/',wait_until='networkidle')
    ok('Home renders product value',page.get_by_role('heading',name='Find opportunities. Make better decisions.').count()==1)
    ok('Dev version remains noindex',page.locator('meta[name="robots"]').get_attribute('content')=='noindex,nofollow')
    ok('Empty source inventory truthful',page.get_by_text('No verified-source jobs in the local cache yet.').count()==1)
    page.goto(BASE+'/tools/salary-savings',wait_until='networkidle')
    page.locator('[name="rent"]').fill('30000');page.locator('[name="food"]').fill('15000');page.locator('[name="transport"]').fill('5000')
    page.get_by_role('button',name='Calculate savings').click()
    ok('Salary calculator computes INR 58,000 after expenses','58,000' in page.locator('#salary-total').inner_text())
    page.goto(BASE+'/tools/application-tracker',wait_until='networkidle')
    ok('Tracker page works',page.get_by_role('heading',name='Application & follow-up tracker').count()==1)
    page.locator('[name="company"]').fill('Example Employer');page.locator('[name="role"]').fill('Cloud Support');page.locator('[name="url"]').fill('https://example.org/careers/support')
    page.locator('[name="followup_date"]').fill('2026-12-01');page.locator('[name="status"]').select_option('applied');page.locator('[name="applied_at"]').fill('2026-11-22')
    page.get_by_role('button',name='Save application').click()
    ok('Manual application saved',page.get_by_text('Cloud Support — Example Employer').count()==1)
    ok('No candidate profile uploaded',page.evaluate('Boolean(localStorage.getItem("overseasjob_applications_v1"))'))
    page.reload(wait_until='networkidle')
    ok('Tracker survives browser reload',page.get_by_text('Cloud Support — Example Employer').count()==1)
    with page.expect_download() as download_event:page.get_by_role('button',name='Export JSON').click()
    ok('Tracker JSON download works',download_event.value.suggested_filename.endswith('.json'))
    with page.expect_download() as download_event:page.get_by_role('button',name='Export calendar reminder').click()
    ok('Calendar reminder download works',download_event.value.suggested_filename.endswith('.ics'))
    page.goto(BASE+'/guides/germany-career-research',wait_until='networkidle')
    ok('Sourced Germany draft page available',page.get_by_text('Federal Employment Agency — professional qualifications').count()==1)
    ok('Unreviewed guide is noindex',page.locator('meta[name="robots"]').get_attribute('content')=='noindex,nofollow')
    # Actual headless Chromium exercises T07–T10 on isolated local PHP preview.
    page.goto(BASE+'/tools/interview-practice',wait_until='networkidle')
    ok('T07 original question displayed',page.locator('#interview-question h3').count()==1)
    page.locator('#interview-rubric input').first.check()
    page.locator('#interview-review').click()
    ok('T07 self-review explained',page.get_by_text('Self-review:',exact=False).count()>=1)
    page.locator('#interview-answer').fill('My own hypothetical practice steps')
    with page.expect_download() as d:page.locator('#interview-export').click()
    ok('T07 local text export',d.value.suggested_filename.endswith('.txt'))
    page.goto(BASE+'/tools/country-checklist',wait_until='networkidle')
    ok('T08 ten generic tasks',page.locator('#checklist-items input[type="checkbox"]').count()==10)
    page.locator('#checklist-items input').first.check()
    page.locator('#checklist-form [name="country"]').select_option('Germany')
    ok('T08 Germany has separate progress',page.locator('#checklist-items input').first.is_checked() is False)
    page.locator('#checklist-form [name="country"]').select_option('UAE')
    ok('T08 UAE progress restored',page.locator('#checklist-items input').first.is_checked())
    with page.expect_download() as d:page.locator('#checklist-export').click()
    ok('T08 local JSON export',d.value.suggested_filename.endswith('.json'))
    page.goto(BASE+'/tools/workproof',wait_until='networkidle')
    page.locator('#portfolio-form [name="name"]').fill('Test Applicant')
    page.locator('#portfolio-form [name="role"]').fill('IT Support')
    page.locator('#portfolio-form [name="p1_title"]').fill('Practice lab')
    page.locator('#portfolio-form [name="p1_description"]').fill('My genuine simulated practice project')
    page.locator('#portfolio-form button[type="submit"]').click()
    ok('T09 preview self-reported',page.get_by_text('Self-reported work; not independently verified.').count()>=1)
    with page.expect_download() as d:page.locator('#portfolio-export').click()
    ok('T09 standalone HTML export',d.value.suggested_filename.endswith('.html'))
    page.goto(BASE+'/tools/career-roadmap',wait_until='networkidle')
    page.locator('#roadmap-form [name="hours"]').fill('3')
    page.locator('#roadmap-form button[type="submit"]').click()
    ok('T10 3 weekly hours yields 12-hour stage',page.get_by_text('Time budget: 12 hours across a four-week study block').count()==3)
    page.locator('#roadmap-note-30').fill('My personal target')
    with page.expect_download() as d:page.locator('#roadmap-export').click()
    ok('T10 personal roadmap export',d.value.suggested_filename.endswith('.json'))
    # Privacy-first daily mission and consent checks run in the isolated browser.
    page.goto(BASE+'/daily',wait_until='networkidle')
    ok('M08 daily question shown',len(page.locator('#daily-prompt').inner_text())>20)
    page.locator('#daily-complete').click()
    ok('M08 self-reported completion saved',page.locator('#daily-complete').is_disabled())
    ok('M08 browser-local progress',page.evaluate('Boolean(localStorage.getItem("overseasjob_daily_v1"))'))
    page.goto(BASE+'/privacy',wait_until='networkidle')
    ok('M09 optional metrics opt-out by default',not page.locator('#privacy-count-optin').is_checked())
    if page.locator('#privacy-count-optin').is_enabled():
        page.locator('#privacy-count-optin').check()
        ok('M09 consent saved on-device',page.evaluate('localStorage.getItem("overseasjob_privacy_v1")')=='yes')
    page.once('dialog',lambda dialog: dialog.accept())
    page.locator('#privacy-delete-all').click()
    ok('M15 all local OverseasJob data deletion',page.evaluate('!Object.keys(localStorage).some(k=>k.startsWith("overseasjob_"))'))
    ok('No browser JavaScript errors',not errs)
    # Real narrow-screen responsive checks. Offscreen content must not create
    # horizontal scrolling that hides critical actions on a typical phone.
    mobile_context=browser.new_context(viewport={'width':390,'height':844},is_mobile=True,has_touch=True,device_scale_factor=1)
    mobile=mobile_context.new_page()
    mobile_errs=[]
    mobile.on('pageerror',lambda e: mobile_errs.append(str(e)))
    for route in ['/', '/jobs', '/tools', '/tools/application-tracker', '/tools/interview-practice', '/daily', '/privacy']:
        mobile.goto(BASE+route,wait_until='networkidle')
        dims=mobile.evaluate('''() => ({viewport: window.innerWidth, content: document.documentElement.scrollWidth})''')
        ok('Mobile 390px no horizontal overflow '+route,dims['content']<=dims['viewport']+3)
    ok('Mobile pages have no uncaught JS errors',not mobile_errs)
    mobile_context.close()
    context.close();browser.close()
print(f'\n{len(passes)} actual Chromium browser checks passed')
